// Builds src/lib/historicalReturns.ts from Robert Shiller's monthly S&P data.
// Run: node scripts/build-historical-returns.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const XLSX = createRequire(import.meta.url)('xlsx');
const SOURCE = 'http://www.econ.yale.edu/~shiller/data/ie_data.xls';

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText}`);
const wb = XLSX.read(new Uint8Array(await res.arrayBuffer()), { type: 'array' });
const rows = XLSX.utils.sheet_to_json(wb.Sheets['Data'], { header: 1, raw: true });

const headerIdx = rows.findIndex(r => r[0] === 'Date');
if (headerIdx < 0) throw new Error('No Date header in the Data sheet');
const header = rows[headerIdx].map(h => (typeof h === 'string' ? h.trim() : h));
const col = name => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`Missing column ${name}`);
  return i;
};
const [iDate, iP, iD, iCpi] = [col('Date'), col('P'), col('D'), col('CPI')];

const months = [];
for (const r of rows.slice(headerIdx + 1)) {
  const [date, p, d, cpi] = [r[iDate], r[iP], r[iD], r[iCpi]];
  if (![date, p, d, cpi].every(v => typeof v === 'number' && Number.isFinite(v))) break;
  const year = Math.floor(date);
  // Shiller writes October as 1871.1, so read the month from two decimals.
  const month = Math.round((date - year) * 100);
  const prev = months.at(-1);
  if (prev) {
    const expected = prev.month === 12 ? [prev.year + 1, 1] : [prev.year, prev.month + 1];
    if (year !== expected[0] || month !== expected[1]) throw new Error(`Gap after ${prev.year}-${prev.month}`);
  }
  months.push({ year, month, p, d, cpi });
}

// Real total-return index: D is an annual dividend rate, so a twelfth is paid each month.
const index = [1];
for (let i = 1; i < months.length; i++) {
  const prev = months[i - 1];
  const cur = months[i];
  index.push(index[i - 1] * ((cur.p + cur.d / 12) / prev.p) * (prev.cpi / cur.cpi));
}

const january = new Map();
months.forEach((m, i) => { if (m.month === 1) january.set(m.year, i); });
const out = [];
for (const [year, i] of january) {
  const next = january.get(year + 1);
  if (next !== undefined) out.push({ year, real: Number((index[next] / index[i] - 1).toFixed(5)) });
}

const body = out.map(r => `  { year: ${r.year}, real: ${r.real} },`).join('\n');
writeFileSync('src/lib/historicalReturns.ts', `// Generated by scripts/build-historical-returns.mjs from Robert Shiller's S&P data
// (${SOURCE}). Annual US stock real total returns, January to January. Do not edit by hand.
export interface HistoricalYear {
  year: number;
  /** Real total return for the year as a fraction, e.g. -0.38. */
  real: number;
}

export const HISTORICAL_REAL_RETURNS: HistoricalYear[] = [
${body}
];
`);
console.log(`Wrote ${out.length} years, ${out[0].year}–${out.at(-1).year}`);
